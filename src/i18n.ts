import { create } from 'zustand'

// Deux langues : le français (celle du code) et l'anglais. Les textes sont écrits en français partout ; `tr` les traduit par
// leur texte français. Un texte absent du dictionnaire reste tel quel (le titre d'une piste, par exemple).
export type Lang = 'fr' | 'en'

const KEY = 'chambre-lofi.lang'
const initial = (): Lang => {
  try {
    const saved = localStorage.getItem(KEY)
    if (saved === 'fr' || saved === 'en') return saved
  } catch {
    // pas de stockage : on suit la langue du navigateur
  }
  return navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en'
}

export const useLang = create<{ lang: Lang; set: (l: Lang) => void }>((set) => ({
  lang: initial(),
  set: (lang) => {
    try {
      localStorage.setItem(KEY, lang)
    } catch {
      // idem
    }
    set({ lang })
  },
}))

const apply = (lang: Lang) => {
  document.documentElement.lang = lang
}
apply(useLang.getState().lang)
useLang.subscribe((s) => apply(s.lang))

