/** Traduit un texte écrit en français dans la langue choisie. Hors composant : lit la langue du moment. */
export const tr = (fr: string) => (useLang.getState().lang === 'en' ? EN[fr] ?? fr : fr)

/** Dans un composant : se réabonne au changement de langue. */
export function useT() {
  const lang = useLang((s) => s.lang)
  return (fr: string) => (lang === 'en' ? EN[fr] ?? fr : fr)
}
